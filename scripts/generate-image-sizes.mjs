// Regenerates lib/imageSizes.ts from every image referenced in lib/projects.ts.
// Reads dimensions and EXIF orientation directly from the JPEG bytes, so the
// result is the *displayed* size (camera-rotated photos have their width and
// height swapped). Run after adding or replacing images:  npm run images:sizes
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const projectsSrc = readFileSync(join(root, "lib/projects.ts"), "utf8");
const paths = [
  ...new Set(projectsSrc.match(/\/images\/[^"']+\.(?:jpe?g)/gi) ?? []),
].sort();

// Returns the EXIF orientation (1–8), or null if this APP1 segment isn't EXIF.
// (Photos often carry a second APP1 segment holding XMP — it must be ignored,
// not treated as "orientation 1", or it would clobber the real value.)
function exifOrientation(buf, start, length) {
  if (buf.toString("latin1", start, start + 6) !== "Exif\0\0") return null;
  const tiff = start + 6;
  const le = buf.toString("latin1", tiff, tiff + 2) === "II";
  const u16 = (o) => (le ? buf.readUInt16LE(o) : buf.readUInt16BE(o));
  const u32 = (o) => (le ? buf.readUInt32LE(o) : buf.readUInt32BE(o));
  const ifd = tiff + u32(tiff + 4);
  if (ifd + 2 > start + length) return 1;
  for (let i = 0, n = u16(ifd); i < n; i++) {
    const entry = ifd + 2 + i * 12;
    if (u16(entry) === 0x0112) return u16(entry + 8);
  }
  return 1;
}

function jpegSize(file) {
  const buf = readFileSync(file);
  if (buf[0] !== 0xff || buf[1] !== 0xd8) throw new Error("not a JPEG");
  let orientation = 1;
  let off = 2;
  while (off < buf.length) {
    if (buf[off] !== 0xff) { off++; continue; }
    const marker = buf[off + 1];
    if (marker === 0xd8 || (marker >= 0xd0 && marker <= 0xd7) || marker === 0x01) {
      off += 2;
      continue;
    }
    const len = buf.readUInt16BE(off + 2);
    if (marker === 0xe1) {
      const o = exifOrientation(buf, off + 4, len - 2);
      if (o !== null) orientation = o;
    }
    // SOF0–SOF15 except DHT (C4), JPG (C8) and DAC (CC) carry the frame size.
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      const h = buf.readUInt16BE(off + 5);
      const w = buf.readUInt16BE(off + 7);
      return orientation >= 5 ? [h, w] : [w, h];
    }
    off += 2 + len;
  }
  throw new Error("no frame header found");
}

const lines = paths.map((p) => {
  const [w, h] = jpegSize(join(root, "public", p));
  return `  "${p}": [${w}, ${h}],`;
});

writeFileSync(
  join(root, "lib/imageSizes.ts"),
  [
    "// AUTO-GENERATED by scripts/generate-image-sizes.mjs — do not edit by hand.",
    "// Displayed [width, height] of each image (EXIF rotation applied). Drives",
    "// next/image dimensions so photos reserve space and never shift on load.",
    "// Regenerate after adding or replacing images:  npm run images:sizes",
    "export const imageSizes: Record<string, [number, number]> = {",
    ...lines,
    "};",
    "",
  ].join("\n"),
);
console.log(`Wrote ${lines.length} image sizes to lib/imageSizes.ts`);
