// Regenerates lib/imagePlaceholders.ts: a tiny (16px-wide) blurred WebP for
// every image referenced in lib/projects.ts, inlined as a data URL. These show
// instantly while the full photo loads ("blur-up"), so the gallery and the
// lightbox never show an empty frame. Each is only a few hundred bytes.
// Run after adding or replacing images:  npm run images:sizes
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const projectsSrc = readFileSync(join(root, "lib/projects.ts"), "utf8");
const paths = [
  ...new Set(projectsSrc.match(/\/images\/[^"']+\.(?:jpe?g)/gi) ?? []),
].sort();

const entries = [];
for (const p of paths) {
  const buf = await sharp(join(root, "public", p))
    .rotate() // honour EXIF orientation, like the browser does
    .resize(16)
    .webp({ quality: 40 })
    .toBuffer();
  entries.push(`  ${JSON.stringify(p)}: "data:image/webp;base64,${buf.toString("base64")}",`);
}

writeFileSync(
  join(root, "lib/imagePlaceholders.ts"),
  `// AUTO-GENERATED by scripts/generate-image-placeholders.mjs — do not edit.
// Run \`npm run images:sizes\` after adding or replacing images.
export const imagePlaceholders: Record<string, string> = {
${entries.join("\n")}
};
`
);
console.log(`Wrote ${entries.length} placeholders to lib/imagePlaceholders.ts`);
